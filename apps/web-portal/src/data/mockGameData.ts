export const CAMPAIGN_STAGES: StageNode[] = (() => {
  const allStages: StageNode[] = [];

  CHAPTERS_META_10.forEach((chMeta) => {
    for (let s = 1; s <= 10; s++) {
      const isBossStage = s === 10;
      const stageId = `stage_${chMeta.chapter}_${s}`;
      const cpRequired = chMeta.baseCP + (s - 1) * chMeta.cpStep;
      const stagePrefix = STAGE_NAME_PREFIXES[s - 1];

      // Chapter 1 stages 1-3 cleared, stage 4 unlocked by default
      const isCleared = chMeta.chapter === 1 && s <= 3;
      const isUnlocked = chMeta.chapter === 1 ? s <= 4 : false;

      const stageDrops = isBossStage
        ? chMeta.bossDrops
        : [
            { rarity: (s <= 3 ? 'Common' : s <= 6 ? 'Fine' : 'Rare') as CardRarity, name: `Đá Cường Hóa ${chMeta.shortTitle}` },
            { rarity: (s <= 5 ? 'Fine' : s <= 8 ? 'Rare' : 'Epic') as CardRarity, name: `Rương Chiến Binh Ải ${chMeta.chapter}-${s}` }
          ];

      allStages.push({
        id: stageId,
        chapter: chMeta.chapter,
        name: `${chMeta.chapter}-${s}: ${stagePrefix} ${isBossStage ? 'TRÙM ĐỊA BÀN' : chMeta.shortTitle.split(':')[1] || ''}`,
        subtitle: isBossStage ? chMeta.bossDesc : `${chMeta.theme} • Khu vực ${s}/10`,
        recommendedCP: cpRequired,
        bossName: isBossStage ? chMeta.bossName : `Tiểu Tướng ${chMeta.shortTitle} #${s}`,
        isCleared,
        isUnlocked,
        drops: stageDrops
      });
    }
  });

  return allStages;
})();


